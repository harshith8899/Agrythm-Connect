export const getDistrictsForState = (stateName) => {
  if (!stateName) return [];
  // Case-insensitive match for convenience
  const matched = Object.keys(INDIA_STATES_AND_DISTRICTS).find(
    (s) => s.toLowerCase() === String(stateName).trim().toLowerCase()
  );
  return matched ? INDIA_STATES_AND_DISTRICTS[matched] : [];
};

